//! `shotlet completions bash`: walks the words typed to find the command,
//! then completes an option's value, an option, or the subcommands,
//! argument choices and file names.

const std = @import("std");
const spec = @import("spec.zig");
const complete = @import("complete.zig");
const W = *std.Io.Writer;

pub fn write(w: W) !void {
    try w.writeAll(
        \\# bash completion for shotlet (generated by `shotlet completions bash`)
        \\_shotlet() {
        \\    local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}
        \\    local cmd="" i
        \\    for ((i = 1; i < COMP_CWORD; i++)); do
        \\        case "$cmd/${COMP_WORDS[i]}" in
        \\
    );
    try complete.each(w, walkCase);
    try w.writeAll(
        \\        esac
        \\    done
        \\    case "$cmd $prev" in
        \\
    );
    try complete.each(w, valueCases);
    try w.writeAll(
        \\    esac
        \\    local words="" opts="" files=0
        \\    case $cmd in
        \\
    );
    try w.writeAll("        \"\") words=\"");
    try topWords(w);
    try w.writeAll("\" opts=\"--help -h --version -V\" ;;\n");
    try complete.each(w, wordsCase);
    try w.writeAll(
        \\    esac
        \\    if [[ $cur == -* ]]; then
        \\        COMPREPLY=($(compgen -W "$opts" -- "$cur"))
        \\    else
        \\        COMPREPLY=($(compgen -W "$words" -- "$cur"))
        \\        if ((files)); then COMPREPLY+=($(compgen -f -- "$cur")); fi
        \\    fi
        \\}
        \\complete -o filenames -F _shotlet shotlet
        \\
    );
}

fn walkCase(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var buf: [64]u8 = undefined;
    const k = complete.key(&buf, parent, c);
    const from = if (parent) |p| p.name else "";
    try w.print("            \"{s}/{s}\"", .{ from, c.name });
    if (parent == null) for (c.aliases) |a| try w.print(" | \"/{s}\"", .{a});
    try w.print(") cmd={s} ;;\n", .{k});
}

fn valueCases(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var kbuf: [64]u8 = undefined;
    const k = complete.key(&kbuf, parent, c);
    var obuf: [32]spec.Option = undefined;
    for (complete.options(c, &obuf)) |o| {
        if (o.value == null) continue;
        try w.print("        \"{s} --{s}\"", .{ k, o.long });
        if (o.short) |s| try w.print(" | \"{s} -{c}\"", .{ k, s });
        try w.writeAll(")");
        if (o.choices.len > 0) {
            try w.writeAll(" COMPREPLY=($(compgen -W \"");
            try spaced(w, o.choices);
            try w.writeAll("\" -- \"$cur\"))");
        } else if (o.kind == .file) {
            try w.writeAll(" COMPREPLY=($(compgen -f -- \"$cur\"))");
        } else try w.writeAll(" :");
        try w.writeAll("; return ;;\n");
    }
}

fn wordsCase(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var kbuf: [64]u8 = undefined;
    try w.print("        \"{s}\") words=\"", .{complete.key(&kbuf, parent, c)});
    for (c.subs, 0..) |s, i| try w.print("{s}{s}", .{ if (i > 0) " " else "", s.name });
    const arg = complete.firstArg(c);
    if (arg) |a| try spaced(w, a.choices);
    try w.writeAll("\" opts=\"");
    var obuf: [32]spec.Option = undefined;
    for (complete.options(c, &obuf), 0..) |o, i| {
        try w.print("{s}--{s}", .{ if (i > 0) " " else "", o.long });
        if (o.short) |s| try w.print(" -{c}", .{s});
    }
    const files = arg != null and arg.?.kind == .file;
    try w.print("\" files={d} ;;\n", .{@intFromBool(files)});
}

fn topWords(w: W) !void {
    var first = true;
    for (&@import("commands.zig").all) |*c| if (!c.internal()) {
        try w.print("{s}{s}", .{ if (first) "" else " ", c.name });
        first = false;
    };
}

fn spaced(w: W, words: []const []const u8) !void {
    for (words, 0..) |s, i| try w.print("{s}{s}", .{ if (i > 0) " " else "", s });
}

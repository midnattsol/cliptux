//! `shotlet completions zsh`: as the bash script, with descriptions.
//! Saved as _shotlet in a directory of $fpath.

const std = @import("std");
const spec = @import("spec.zig");
const complete = @import("complete.zig");
const commands = @import("commands.zig");
const W = *std.Io.Writer;

pub fn write(w: W) !void {
    try w.writeAll(
        \\#compdef shotlet
        \\# zsh completion for shotlet (generated by `shotlet completions zsh`)
        \\_shotlet() {
        \\    local cmd="" i
        \\    for ((i = 2; i < CURRENT; i++)); do
        \\        case "$cmd/${words[i]}" in
        \\
    );
    try complete.each(w, walkCase);
    try w.writeAll(
        \\        esac
        \\    done
        \\    local cur=${words[CURRENT]} prev=${words[CURRENT-1]}
        \\    case "$cmd $prev" in
        \\
    );
    try complete.each(w, valueCases);
    try w.writeAll(
        \\    esac
        \\    local -a subs opts
        \\    local files=0
        \\    case $cmd in
        \\        "") subs=(
    );
    for (&commands.all) |*c| if (!c.internal()) try item(w, c.name, c.summary);
    try w.writeAll(") opts=(");
    for (complete.top_options) |o| try optionItems(w, o);
    try w.writeAll(") ;;\n");
    try complete.each(w, wordsCase);
    try w.writeAll(
        \\    esac
        \\    if [[ $cur == -* ]]; then
        \\        _describe -t options option opts
        \\    else
        \\        _describe -t commands command subs
        \\        if ((files)); then _files; fi
        \\    fi
        \\}
        \\_shotlet "$@"
        \\
    );
}

fn walkCase(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var buf: [64]u8 = undefined;
    const from = if (parent) |p| p.name else "";
    try w.print("            \"{s}/{s}\"", .{ from, c.name });
    if (parent == null) for (c.aliases) |a| try w.print(" | \"/{s}\"", .{a});
    try w.print(") cmd={s} ;;\n", .{complete.key(&buf, parent, c)});
}

fn valueCases(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var kbuf: [64]u8 = undefined;
    const k = complete.key(&kbuf, parent, c);
    var obuf: [32]spec.Option = undefined;
    for (complete.options(c, &obuf)) |o| {
        const v = o.value orelse continue;
        try w.print("        \"{s} --{s}\"", .{ k, o.long });
        if (o.short) |s| try w.print(" | \"{s} -{c}\"", .{ k, s });
        try w.writeAll(") ");
        if (o.choices.len > 0) {
            try w.writeAll("compadd --");
            for (o.choices) |ch| try w.print(" {s}", .{ch});
        } else if (o.kind == .file) {
            try w.writeAll("_files");
        } else try w.print("_message {s}", .{v});
        try w.writeAll("; return ;;\n");
    }
}

fn wordsCase(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var kbuf: [64]u8 = undefined;
    try w.print("        \"{s}\") subs=(", .{complete.key(&kbuf, parent, c)});
    for (c.subs) |s| try item(w, s.name, s.summary);
    const arg = complete.firstArg(c);
    if (arg) |a| for (a.choices) |ch| try item(w, ch, a.help);
    try w.writeAll(") opts=(");
    var obuf: [32]spec.Option = undefined;
    for (complete.options(c, &obuf)) |o| try optionItems(w, o);
    const files = arg != null and arg.?.kind == .file;
    try w.print(") files={d} ;;\n", .{@intFromBool(files)});
}

fn optionItems(w: W, o: spec.Option) !void {
    var buf: [64]u8 = undefined;
    try item(w, std.fmt.bufPrint(&buf, "--{s}", .{o.long}) catch o.long, o.help);
    if (o.short) |s| try item(w, std.fmt.bufPrint(&buf, "-{c}", .{s}) catch o.long, o.help);
}

/// 'name:description', a colon in the name escaped.
fn item(w: W, name: []const u8, desc: []const u8) !void {
    var buf: [256]u8 = undefined;
    var fw: std.Io.Writer = .fixed(&buf);
    for (name) |ch| {
        if (ch == ':') fw.writeByte('\\') catch {};
        fw.writeByte(ch) catch {};
    }
    fw.print(":{s}", .{desc}) catch {};
    try w.writeByte(' ');
    try complete.quoted(w, fw.buffered(), false);
}

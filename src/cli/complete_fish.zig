//! `shotlet completions fish`: one `complete` line per command, option
//! and choice, each under the condition of its command.

const std = @import("std");
const spec = @import("spec.zig");
const complete = @import("complete.zig");
const W = *std.Io.Writer;

pub fn write(w: W) !void {
    try w.writeAll(
        \\# fish completion for shotlet (generated by `shotlet completions fish`)
        \\complete -c shotlet -f
        \\
    );
    for (complete.top_options) |o| try option(w, "__fish_use_subcommand", o);
    try complete.each(w, commandLines);
}

fn commandLines(w: W, parent: ?*const spec.Command, c: *const spec.Command) !void {
    var cbuf: [256]u8 = undefined;
    var ibuf: [256]u8 = undefined;
    // the condition where this command's name completes, and the one
    // where its own options and arguments do
    const offer, const inside = if (parent) |p| .{
        try subsCondition(&cbuf, p),
        try std.fmt.bufPrint(&ibuf, "__fish_seen_subcommand_from {s}; and __fish_seen_subcommand_from {s}", .{ p.name, c.name }),
    } else .{
        "__fish_use_subcommand",
        try std.fmt.bufPrint(&ibuf, "__fish_seen_subcommand_from {s}", .{c.name}),
    };
    try w.print("complete -c shotlet -n '{s}' -a {s} -d ", .{ offer, c.name });
    try complete.quoted(w, c.summary, true);
    try w.writeAll("\n");
    var obuf: [32]spec.Option = undefined;
    for (complete.options(c, &obuf)) |o| try option(w, inside, o);
    if (complete.firstArg(c)) |a| try argument(w, inside, a);
}

/// Under `p` while none of its subcommands is typed yet.
fn subsCondition(buf: []u8, p: *const spec.Command) ![]const u8 {
    var fw: std.Io.Writer = .fixed(buf);
    try fw.print("__fish_seen_subcommand_from {s}; and not __fish_seen_subcommand_from", .{p.name});
    for (p.subs) |s| try fw.print(" {s}", .{s.name});
    return fw.buffered();
}

fn option(w: W, cond: []const u8, o: spec.Option) !void {
    try w.print("complete -c shotlet -n '{s}' -l {s}", .{ cond, o.long });
    if (o.short) |s| try w.print(" -s {c}", .{s});
    if (o.value != null) {
        if (o.choices.len > 0) {
            try w.writeAll(" -x -a ");
            try choices(w, o.choices);
        } else if (o.kind == .file) {
            try w.writeAll(" -r -F");
        } else try w.writeAll(" -x");
    }
    try w.writeAll(" -d ");
    try complete.quoted(w, o.help, true);
    try w.writeAll("\n");
}

fn argument(w: W, cond: []const u8, a: spec.Arg) !void {
    if (a.kind == .file) return w.print("complete -c shotlet -n '{s}' -F\n", .{cond});
    if (a.choices.len == 0) return;
    try w.print("complete -c shotlet -n '{s}' -a ", .{cond});
    try choices(w, a.choices);
    try w.writeAll(" -d ");
    try complete.quoted(w, a.help, true);
    try w.writeAll("\n");
}

fn choices(w: W, list: []const []const u8) !void {
    var buf: [256]u8 = undefined;
    var fw: std.Io.Writer = .fixed(&buf);
    for (list, 0..) |s, i| fw.print("{s}{s}", .{ if (i > 0) " " else "", s }) catch {};
    try complete.quoted(w, fw.buffered(), true);
}
